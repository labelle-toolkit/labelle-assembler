// (design §8). Its `resolve_target` is DISTINCT from android's: besides the
// `ResolvedTarget` it also runs `xcrun` SDK discovery and returns the SDK PATH,
// because plugin `b.dependency` calls consume it (`build_files.zig:341`) and it
// therefore must be resolved BEFORE any dependency (design §4 review-correction
// #6). `post_wire` then consumes that SDK path (residual (b): `configureSdkPaths`
// / `addExeSdkPaths`); the iOS frameworks + `link_libc` are DECLARATIVE
// (`.frameworks.ios`), emitted here. Like android this is a GOLDEN cell (§7): the
// residual moved into the hook and the unrolled core-diamond overrides became the
// generic `unifyCoreDiamond` loop, so the text legitimately DIFFERS from the enum
// `header_ios`/`ios_deps`/`backend_sokol_ios`/`ios_link` path.
