/// Transcription of `backends/sokol/src/gfx/font.zig` — the font-capable
/// backend shape, MINUS `unloadFontAtlas` — the plain and registry-aware
/// variants below append their own so the registry one can timestamp the
/// atlas destruction. `decodeFont` ECHOES the marshalled params back through
/// `DecodedFont` so the test can prove the bridge carried real values.
const backend_font_core =
    \\const std = @import("std");
    \\
    \\pub const CodepointRange = extern struct {
    \\    first: u32,
    \\    last: u32,
    \\};
    \\
    \\pub const FontBakeParams = struct {
    \\    pixel_height: f32 = 16,
    \\    ranges: []const CodepointRange = &.{.{ .first = 0x20, .last = 0x7F }},
    \\    atlas_width: u32 = 512,
    \\    atlas_height: u32 = 512,
    \\};
    \\
    \\pub const Glyph = extern struct {
    \\    x0: u16 = 0,
    \\    y0: u16 = 0,
    \\    x1: u16 = 0,
    \\    y1: u16 = 0,
    \\    xoff: f32 = 0,
    \\    yoff: f32 = 0,
    \\    advance: f32 = 0,
    \\};
    \\
    \\pub const CodepointEntry = extern struct {
    \\    codepoint: u32 = 0,
    \\    glyph_index: u32 = 0,
    \\};
    \\
    \\pub const KernPair = extern struct {
    \\    first: u32 = 0,
    \\    second: u32 = 0,
    \\    advance: f32 = 0,
    \\};
    \\
    \\pub const FontAtlas = struct { texture: u32 };
    \\
    \\pub const DecodedFont = struct {
    \\    bitmap: []u8,
    \\    width: u32,
    \\    height: u32,
    \\    glyphs: []Glyph,
    \\    codepoint_index: []const CodepointEntry,
    \\    ascent: f32,
    \\    descent: f32,
    \\    line_gap: f32,
    \\    line_height: f32,
    \\    kerning: []const KernPair,
    \\};
    \\
    \\pub fn decodeFont(
    \\    file_type: [:0]const u8,
    \\    data: []const u8,
    \\    params: *const FontBakeParams,
    \\    allocator: std.mem.Allocator,
    \\) !DecodedFont {
    \\    _ = file_type;
    \\    _ = data;
    \\    // Echo the bridged values back out: atlas dims and pixel height
    \\    // ride the numeric fields, and the LAST codepoint range's bounds
    \\    // ride the vertical metrics. If the ranges bridge dropped or
    \\    // garbled an element these come back wrong, which is the point —
    \\    // typechecking alone would not catch it.
    \\    const last = params.ranges[params.ranges.len - 1];
    \\    return .{
    \\        .bitmap = try allocator.alloc(u8, params.ranges.len),
    \\        .width = params.atlas_width,
    \\        .height = params.atlas_height,
    \\        .glyphs = try allocator.alloc(Glyph, 0),
    \\        .codepoint_index = try allocator.alloc(CodepointEntry, 0),
    \\        .ascent = @floatFromInt(last.first),
    \\        .descent = @floatFromInt(last.last),
    \\        .line_gap = 0,
    \\        .line_height = params.pixel_height,
    \\        .kerning = try allocator.alloc(KernPair, 0),
    \\    };
    \\}
    \\
    \\pub fn uploadFontAtlas(decoded: DecodedFont) !FontAtlas {
    \\    return .{ .texture = decoded.width };
    \\}
;

/// A font-capable backend that has NOT opted into the registry seam — the
/// sokol/bgfx shape today. Every `registerCatalogFont` reference the adapter
/// emits must stay comptime-dead here.
const backend_with_fonts = backend_font_core ++
    \\
    \\pub fn unloadFontAtlas(atlas: FontAtlas) void {
    \\    _ = atlas;
    \\}
;

/// The shape a backend takes once it opts into the catalog font registry
/// (labelle-bgfx#85): `backend_with_fonts` plus the
/// `registerCatalogFont` / `unregisterCatalogFont` pair, recording what it
/// was handed and WHEN, so the test can assert on the handle arithmetic and
/// on the register-before-destroy ordering rather than on mere compilation.
const registry_decls =
    \\
    \\pub var register_count: u32 = 0;
    \\pub var last_registered_handle: u32 = 0;
    \\pub var last_registered_atlas: ?FontAtlas = null;
    \\pub var last_unregistered_handle: u32 = 0;
    \\pub var seq: u32 = 0;
    \\pub var registered_at: u32 = 0;
    \\pub var unregistered_at: u32 = 0;
    \\pub var destroyed_at: u32 = 0;
    \\
    \\pub fn registerCatalogFont(handle: u32, atlas: FontAtlas) void {
    \\    register_count += 1;
    \\    last_registered_handle = handle;
    \\    last_registered_atlas = atlas;
    \\    seq += 1;
    \\    registered_at = seq;
    \\}
    \\
    \\pub fn unregisterCatalogFont(handle: u32) void {
    \\    last_unregistered_handle = handle;
    \\    seq += 1;
    \\    unregistered_at = seq;
    \\}
    \\
    \\pub fn noteDestroy() void {
    \\    seq += 1;
    \\    destroyed_at = seq;
    \\}
;

/// `unloadFontAtlas` that timestamps the atlas destruction, so the test can
/// assert the registry entry is retired STRICTLY BEFORE the GPU atlas dies.
const registry_unload =
    \\
    \\pub fn unloadFontAtlas(atlas: FontAtlas) void {
    \\    _ = atlas;
    \\    noteDestroy();
    \\}
;

/// Font-capable backend that has opted into the registry seam.
const backend_with_font_registry = backend_font_core ++ registry_decls ++ registry_unload;

/// The bgfx shape: a graphics backend with NO font decls at all — not even
/// `FontAtlas`. Every reference the adapter makes to a font type must stay
/// behind a comptime-false `@hasDecl` guard, or a project that merely
/// declares a font resource stops compiling on this backend.
const backend_without_fonts =
    \\pub const nothing_here = {};
;

/// Harness: the REAL emitted block spliced into a function, plus tests that
/// exercise the installed vtable.
fn harnessSource(allocator: std.mem.Allocator, block: []const u8, extra_tests: []const u8) ![]u8 {
    return std.fmt.allocPrint(allocator,
        \\const std = @import("std");
        \\const engine = @import("engine.zig");
        \\const BackendGfx = @import("backend.zig");
        \\
        \\fn wire() void {{
        \\{s}
        \\}}
        \\
        \\{s}
    , .{ block, extra_tests });
}

const capable_tests =
    \\test "the adapter satisfies engine.FontBackend and bridges FontBakeParams" {
    \\    wire();
    \\    const b = engine.FontLoader.currentBackend().?;
    \\    const ranges = [_]engine.CodepointRange{
    \\        .{ .first = 0x20, .last = 0x7F },
    \\        .{ .first = 0x400, .last = 0x450 },
    \\    };
    \\    const alloc = std.testing.allocator;
    \\    const decoded = try b.decode("ttf", "fake-ttf-bytes", .{
    \\        .pixel_height = 24,
    \\        .ranges = &ranges,
    \\        .atlas_width = 256,
    \\        .atlas_height = 128,
    \\    }, alloc);
    \\    defer alloc.free(decoded.bitmap);
    \\    defer alloc.free(decoded.glyphs);
    \\    defer alloc.free(decoded.codepoint_index);
    \\    defer alloc.free(decoded.kerning);
    \\
    \\    try std.testing.expectEqual(@as(u32, 256), decoded.width);
    \\    try std.testing.expectEqual(@as(u32, 128), decoded.height);
    \\    try std.testing.expectEqual(@as(f32, 24), decoded.line_height);
    \\    // Both ranges arrived, and the last one's bounds survived the
    \\    // plain-struct -> extern-struct element copy.
    \\    try std.testing.expectEqual(@as(usize, 2), decoded.bitmap.len);
    \\    try std.testing.expectEqual(@as(f32, 0x400), decoded.ascent);
    \\    try std.testing.expectEqual(@as(f32, 0x450), decoded.descent);
    \\}
    \\
    \\test "upload/unload round-trip through the slot table" {
    \\    wire();
    \\    const b = engine.FontLoader.currentBackend().?;
    \\    const id = try b.upload(.{
    \\        .bitmap = &.{},
    \\        .width = 7,
    \\        .height = 1,
    \\        .glyphs = &.{},
    \\        .codepoint_index = &.{},
    \\        .ascent = 0,
    \\        .descent = 0,
    \\        .line_gap = 0,
    \\        .line_height = 0,
    \\        .kerning = &.{},
    \\    });
    \\    try std.testing.expectEqual(@as(u16, 1), id.generation);
    \\    b.unload(id);
    \\}
