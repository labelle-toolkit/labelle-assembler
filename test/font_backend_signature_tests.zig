//! `FontBackendAdapter` COMPILE + RUN acceptance (labelle-assembler#700).
//!
//! `test/backend_wiring_tests.zig` already pins the emitted strings for the
//! font block — and that family of test is exactly what let #700 through for
//! the whole life of the feature. Every one of those asserts passed while
//! declaring a single `.font` resource in `project.labelle` failed to compile
//! on EVERY assembler + engine pairing ever released:
//!
//!   main.zig: error: expected type '*const fn ([:0]const u8, []const u8,
//!     assets.loaders.font.FontBakeParams, mem.Allocator) T',
//!   found '*const fn ([:0]const u8, []const u8, ?*const anyopaque,
//!     mem.Allocator) T'
//!       .decode = FontBackendAdapter.decode,
//!
//! A string pin cannot see that, because the emitted text was internally
//! consistent — it just did not satisfy `engine.FontBackend`. So this suite
//! takes the #586 / #691 / i18n-sentinel route instead: it renders the REAL
//! block through `writeFontBackendWiring`, splices it into a harness beside
//! a stub `engine` and a stub `BackendGfx`, and drives `zig test` on it
//! through the `test_options.zig_exe` seam. The generated bytes are compiled
//! and RUN; a signature regression is a compile error inside the harness and
//! therefore a failing test here.
//!
//! ## What the stubs mirror, and why hand-mirroring is safe here
//!
//! The assembler takes no dependency on labelle-engine, so the harness cannot
//! `@import` the real thing without a network fetch (the suite's hermeticity
//! rule). The two stubs are therefore transcriptions:
//!
//!   * `engine.zig` mirrors labelle-engine `src/assets/loaders/font.zig` —
//!     `FontBakeParams`, `CodepointRange`, `DecodedFont`, `FontId`, and the
//!     `FontBackend` vtable with `decode` taking `FontBakeParams` BY VALUE.
//!     That shape is not a guess: `FontBackend` was born typed in
//!     labelle-engine#529 (commit c7b6fcb, first released in engine v1.36.0)
//!     and every later commit touching that file keeps it, verified through
//!     v2.15.0. Engines older than v1.36.0 have no `FontLoader.setBackend`
//!     at all, so v1.36.0 is the hard floor for a `.font` resource and
//!     there is exactly ONE signature to satisfy above it.
//!   * `backend.zig` mirrors `backends/sokol/src/gfx/font.zig` — an `extern
//!     struct` `CodepointRange` and a `decodeFont` taking
//!     `*const FontBakeParams`.
//!
//! ## The two backends
//!
//! Both shapes that ship today are covered:
//!
//!   * a FONT-CAPABLE backend (sokol): the adapter must typecheck AND the
//!     marshal must actually carry the values across — the stub echoes the
//!     params it received back through `DecodedFont` so the test asserts on
//!     the bridged `pixel_height` / `ranges` / atlas dims rather than on the
//!     mere fact that it compiled. `CodepointRange` crosses a plain-struct →
//!     `extern struct` boundary, so it needs a real element-by-element copy;
//!     a `@ptrCast` there would be undefined.
//!   * a FONT-LESS backend (bgfx, which declares no font decls whatsoever):
//!     the `@hasDecl` guards must keep the whole marshal comptime-dead, so
//!     the block still compiles and `decode` reports
//!     `error.FontBackendNotImplemented`.

