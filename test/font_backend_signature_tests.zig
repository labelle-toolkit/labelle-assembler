fn writeFileIn(dir: std.Io.Dir, rel: []const u8, body: []const u8) !void {
    if (std.fs.path.dirname(rel)) |sub| try dir.createDirPath(io, sub);
    var f = try dir.createFile(io, rel, .{});
    defer f.close(io);
    try f.writeStreamingAll(io, body);
}

/// Render the shipped font wiring block exactly as `buildSetupCode` /
/// `buildCallbackInitCode` do (same 4-space indent).
fn renderFontWiring(allocator: std.mem.Allocator) ![]u8 {
    var alloc_writer: std.Io.Writer.Allocating = .init(allocator);
    errdefer alloc_writer.deinit();
    var ctx = h.emptyCodegen(allocator);
    try ctx.writeFontBackendWiring(&alloc_writer.writer, "    ");
    return alloc_writer.toOwnedSlice();
}

